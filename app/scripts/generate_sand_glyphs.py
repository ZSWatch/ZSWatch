"""Generates the grains that the digits of the Sand watchface fall apart into: one bit per grain.

Run from app/: python scripts/generate_sand_glyphs.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT = "lvgl_editor/fonts/Montserrat-Medium.ttf"
OUT = "src/ui/watchfaces/sand/sand_glyphs.h"
# The time is drawn with zsw_font_48 (see generate_fonts.sh): same font, size and line box here,
# so that a digit and its grains cover the same pixels.
FONT_SIZE = 48
LINE_HEIGHT = 48
BASE_LINE = 7
# Each digit gets a slot this wide and is centered in it
SLOT_WIDTH = 32
# Pixels per grain. A grain is sand when more than a third of it is covered.
CELL = 2
THRESHOLD = 85

WIDTH = SLOT_WIDTH // CELL
HEIGHT = LINE_HEIGHT // CELL


def render(font, digit):
    image = Image.new("L", (SLOT_WIDTH, LINE_HEIGHT), 0)
    draw = ImageDraw.Draw(image)
    x = (SLOT_WIDTH - font.getlength(digit)) / 2
    draw.text((x, LINE_HEIGHT - BASE_LINE), digit, font=font, fill=255, anchor="ls")
    small = image.resize((WIDTH, HEIGHT), Image.BOX)
    return [[small.getpixel((x, y)) > THRESHOLD for x in range(WIDTH)] for y in range(HEIGHT)]


def main():
    font = ImageFont.truetype(FONT, FONT_SIZE)

    lines = [
        "/* Generated by scripts/generate_sand_glyphs.py, do not edit. */",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define SAND_GLYPH_SLOT_PX  {SLOT_WIDTH}",
        f"#define SAND_GLYPH_WIDTH    {WIDTH}",
        f"#define SAND_GLYPH_HEIGHT   {HEIGHT}",
        "",
        "/* One row per entry, the leftmost grain in the highest of the SAND_GLYPH_WIDTH bits. */",
        "static const uint16_t sand_glyphs[10][SAND_GLYPH_HEIGHT] = {",
    ]
    for digit in "0123456789":
        rows = render(font, digit)
        lines.append(f"    /* {digit} */")
        lines.append("    {")
        for row in rows:
            value = sum(1 << (WIDTH - 1 - x) for x, on in enumerate(row) if on)
            lines.append(f"        0x{value:04X}, /* {''.join('#' if on else '.' for on in row)} */")
        lines.append("    },")
    lines.append("};")
    Path(OUT).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()

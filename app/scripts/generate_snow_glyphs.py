"""Generates the digits of the Snow watchface: one bit per grain.

Run from app/: python scripts/generate_snow_glyphs.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT = "lvgl_editor/fonts/Montserrat-Medium.ttf"
OUT = "src/ui/watchfaces/snow/snow_glyphs.h"
WIDTH = 18
HEIGHT = 27
# Each grain is rendered as SCALE x SCALE pixels and is snow when more than half of it is covered.
SCALE = 8
# The font weight in pixels at render scale, to get strokes about three grains wide.
EMBOLDEN = 3


def render(font, digit):
    image = Image.new("L", (WIDTH * SCALE, HEIGHT * SCALE), 0)
    draw = ImageDraw.Draw(image)
    left, top, right, bottom = draw.textbbox((0, 0), digit, font=font, stroke_width=EMBOLDEN)
    x = (WIDTH * SCALE - (right - left)) // 2 - left
    draw.text((x, -top), digit, font=font, fill=255, stroke_width=EMBOLDEN, stroke_fill=255)
    small = image.resize((WIDTH, HEIGHT), Image.BOX)
    return [[small.getpixel((x, y)) > 127 for x in range(WIDTH)] for y in range(HEIGHT)]


def main():
    # Size the font so that the tallest digit fills the height
    size = 10
    while True:
        font = ImageFont.truetype(FONT, size + 1)
        box = font.getbbox("0", stroke_width=EMBOLDEN)
        if box[3] - box[1] > HEIGHT * SCALE:
            break
        size += 1
    font = ImageFont.truetype(FONT, size)

    lines = [
        "/* Generated by scripts/generate_snow_glyphs.py, do not edit. */",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define SNOW_GLYPH_WIDTH    {WIDTH}",
        f"#define SNOW_GLYPH_HEIGHT   {HEIGHT}",
        "",
        "/* One row per entry, the leftmost grain in the highest of the SNOW_GLYPH_WIDTH bits. */",
        "static const uint32_t snow_glyphs[10][SNOW_GLYPH_HEIGHT] = {",
    ]
    for digit in "0123456789":
        rows = render(font, digit)
        lines.append(f"    /* {digit} */")
        lines.append("    {")
        for row in rows:
            value = sum(1 << (WIDTH - 1 - x) for x, on in enumerate(row) if on)
            lines.append(f"        0x{value:05X}, /* {''.join('#' if on else '.' for on in row)} */")
        lines.append("    },")
    lines.append("};")
    Path(OUT).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()

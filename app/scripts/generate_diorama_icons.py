"""Generates the small icons of the Diorama watchface as masks: how much of each pixel is covered.

They are drawn on the lake and next to the date, straight into the landscape, in the color the
watchface picks.

Run from app/: python scripts/generate_diorama_icons.py
"""

from PIL import Image, ImageDraw

OUT = "src/ui/watchfaces/diorama/diorama_icons.h"
# The icons are drawn this many times larger and scaled down, for smooth edges
SCALE = 8


class Icon:
    def __init__(self, name, width, height):
        self.name = name
        self.image = Image.new("L", (width * SCALE, height * SCALE), 0)
        self.draw = ImageDraw.Draw(self.image)

    def s(self, *values):
        return [v * SCALE for v in values]

    def ellipse(self, cx, cy, rx, ry):
        self.draw.ellipse(self.s(cx - rx, cy - ry, cx + rx, cy + ry), fill=255)

    def rect(self, x, y, w, h, radius=0, outline=0):
        if outline:
            self.draw.rounded_rectangle(self.s(x, y, x + w, y + h), radius * SCALE, outline=255,
                                        width=round(outline * SCALE))
        else:
            self.draw.rounded_rectangle(self.s(x, y, x + w, y + h), radius * SCALE, fill=255)

    def polygon(self, points):
        self.draw.polygon([(x * SCALE, y * SCALE) for x, y in points], fill=255)

    def line(self, x1, y1, x2, y2, width):
        self.draw.line(self.s(x1, y1, x2, y2), fill=255, width=round(width * SCALE))

    def pixels(self):
        small = self.image.resize((self.image.width // SCALE, self.image.height // SCALE), Image.BOX)
        return small.width, small.height, list(small.getdata())


def main():
    icons = []

    icon = Icon("thermometer", 7, 12)
    icon.rect(2, 0, 3, 8, 1.5)
    icon.ellipse(3.5, 9, 3, 3)
    icons.append(icon)

    icon = Icon("steps", 11, 13)
    for dx, dy in ((0, 3), (6, 0)):
        icon.ellipse(dx + 2.5, dy + 3.2, 2.3, 3.2)
        icon.ellipse(dx + 2.5, dy + 8.2, 1.6, 1.6)
    icons.append(icon)

    # The frame of the battery. The watchface fills it to the charge.
    icon = Icon("battery", 20, 10)
    icon.rect(0, 0, 17.5, 10, 2.4, outline=1.25)
    icon.rect(18.25, 3, 1.5, 4, 0.6)
    icons.append(icon)

    icon = Icon("bolt", 7, 8)
    icon.polygon([(4.6, 0), (0.2, 4.6), (3, 4.6), (2.2, 8), (6.8, 3.2), (3.9, 3.2)])
    icons.append(icon)

    icon = Icon("bell", 10, 12)
    icon.polygon([(0.5, 9), (2, 7.2), (2, 4.6), (8, 4.6), (8, 7.2), (9.5, 9)])
    icon.ellipse(5, 4.6, 3, 3)
    icon.rect(4.4, 0.3, 1.2, 1.6)
    icon.draw.pieslice(icon.s(3.5, 8.5, 6.5, 11.5), 0, 180, fill=255)
    icons.append(icon)

    icon = Icon("phone_off", 11, 12)
    icon.rect(2.6, 0.6, 6, 10.4, 1.6, outline=1.2)
    icon.line(0.7, 10.6, 10.3, 0.9, 1.4)
    icons.append(icon)

    out = [
        "/*",
        " * Generated by scripts/generate_diorama_icons.py, do not edit.",
        " * SPDX-License-Identifier: GPL-3.0-only",
        " */",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "/* How much of each pixel the icon covers, of 255, a row at a time */",
        "typedef struct {",
        "    uint8_t width;",
        "    uint8_t height;",
        "    const uint8_t *cover;",
        "} diorama_icon_t;",
        "",
    ]
    for icon in icons:
        width, height, pixels = icon.pixels()
        out.append("static const uint8_t diorama_icon_{}_cover[{}] = {{".format(icon.name, len(pixels)))
        for y in range(height):
            out.append("    " + ", ".join("{:3d}".format(v) for v in pixels[y * width:(y + 1) * width]) + ",")
        out.append("};")
        out.append("")
        out.append("static const diorama_icon_t diorama_icon_{0} = {{ {1}, {2}, diorama_icon_{0}_cover }};".format(
            icon.name, width, height))
        out.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
